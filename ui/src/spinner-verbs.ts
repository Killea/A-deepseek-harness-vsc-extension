/** Locale code → verb array. */
const VERBS_BY_LOCALE: Record<string, readonly string[]> = {
  en: EN_VERBS,
  'zh-cn': ZH_CN_VERBS,
  'zh-tw': ZH_TW_VERBS,
  ja: JA_VERBS,
  de: DE_VERBS,
  fr: FR_VERBS,
  es: ES_VERBS,
}

/**
 * Get the spinner verb array for a locale. Falls back to English for
 * unknown locales. The returned array is guaranteed non-empty.
 */
export function getSpinnerVerbs(locale: string): readonly string[] {
  return VERBS_BY_LOCALE[locale] ?? EN_VERBS;
}
